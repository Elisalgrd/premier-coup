"""Build original French male narration; never sends a user's game or data.

Requires edge-tts and ffprobe. Optional --deps PATH for an existing edge-tts install.
Audio filenames contain a content hash so an old PWA cache cannot serve old speech.
"""
import asyncio, hashlib, json, pathlib, ssl, subprocess, sys

if '--deps' in sys.argv:
    sys.path.insert(0, sys.argv[sys.argv.index('--deps') + 1])
import edge_tts
import edge_tts.communicate as tts_module
tts_module._SSL_CTX = ssl.create_default_context()

VOICE, RATE = 'fr-FR-HenriNeural', '-3%'
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'videos' / 'coach'
OUT.mkdir(parents=True, exist_ok=True)
source = "import {coachWords} from './src/play/coach-words.js'; import {essentialsWords} from './src/learn/essentials.js'; console.log(JSON.stringify({...coachWords,...essentialsWords}));"
jobs = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', source], cwd=ROOT, encoding='utf8'))

async def main():
    manifest = {}
    for key, text in jobs.items():
        digest = hashlib.sha256((VOICE + RATE + text).encode()).hexdigest()[:16]
        target = OUT / (key + '-' + digest + '.mp3')
        if not target.exists():
            for attempt in range(3):
                try:
                    temporary = target.with_suffix('.part')
                    await edge_tts.Communicate(text, VOICE, rate=RATE, connect_timeout=15, receive_timeout=35).save(str(temporary))
                    if temporary.stat().st_size < 1000:
                        raise RuntimeError('Incomplete audio')
                    temporary.replace(target)
                    break
                except Exception:
                    if attempt == 2:
                        raise
                    await asyncio.sleep(2)
        duration = float(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0',str(target)],encoding='utf8').strip())
        manifest[key] = {'file':target.relative_to(ROOT).as_posix(), 'duration':round(duration,3), 'text':text, 'voice':VOICE, 'hash':digest}
        print('Ready: ' + key, flush=True)
    (ROOT / 'src' / 'play' / 'coach-audio.js').write_text('// Generated by scripts/build-coach-audio.py; original educational narration.\nexport const coachAudio = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf8')
    print(str(len(manifest)) + ' clips ready.', flush=True)

asyncio.run(main())
